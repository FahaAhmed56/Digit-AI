"""Train the digit recognizer, save charts, and export weights for the web app.

    python training/train.py
"""
import json
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
from sklearn.datasets import load_digits
from sklearn.model_selection import train_test_split

from network import NeuralNetwork
from preprocess import augment, normalize

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "screenshots"
EPOCHS, BATCH, HIDDEN, COPIES = 60, 64, 128, 12


def main():
    digits = load_digits()                         # 1,797 real handwritten digits, 8x8 pixels
    raw = digits.data / 16.0                       # scale pixels 0..16 -> 0..1
    raw_train, raw_test, y_train0, y_test = train_test_split(raw, digits.target, test_size=0.2, random_state=42, stratify=digits.target)

    # Test set: original digits, passed through the same pipeline the web app uses
    X_test = np.array([normalize(np.clip(__import__("scipy").ndimage.zoom(r.reshape(8, 8), 4, order=1), 0, 1)) for r in raw_test])
    # Training set: COPIES randomly distorted versions of every training digit, same pipeline
    rng_aug = np.random.default_rng(0)
    X_train = np.array([normalize(augment(r, rng_aug)) for r in raw_train for _ in range(COPIES)])
    y_train = np.repeat(y_train0, COPIES)
    print(f"Training on {len(X_train):,} augmented images ({len(raw_train)} originals x {COPIES}), testing on {len(X_test)} unseen")

    net = NeuralNetwork(n_hidden=HIDDEN)
    rng = np.random.default_rng(1)
    history = {"train_loss": [], "test_loss": [], "train_acc": [], "test_acc": []}

    for epoch in range(1, EPOCHS + 1):
        order = rng.permutation(len(X_train))
        for start in range(0, len(order), BATCH):
            idx = order[start:start + BATCH]
            net.forward(X_train[idx])
            net.step(net.backward(y_train[idx]))

        tr_p, te_p = net.forward(X_train), net.forward(X_test)
        history["train_loss"].append(net.loss(tr_p, y_train))
        history["test_loss"].append(net.loss(te_p, y_test))
        history["train_acc"].append((tr_p.argmax(1) == y_train).mean())
        history["test_acc"].append((te_p.argmax(1) == y_test).mean())
        if epoch % 10 == 0 or epoch == 1:
            print(f"epoch {epoch:3d}  loss {history['train_loss'][-1]:.3f}  "
                  f"train {history['train_acc'][-1]:.1%}  test {history['test_acc'][-1]:.1%}")

    preds = net.predict(X_test)
    test_acc = (preds == y_test).mean()
    print(f"\nFinal test accuracy: {test_acc:.2%} on {len(y_test)} unseen digits")

    # ---------- export model for the browser ----------
    (ROOT / "web" / "model.js").write_text(
        "// Auto-generated by training/train.py\nconst MODEL = " + json.dumps(net.to_dict()) + ";\n")
    json.dump({k: [round(float(v), 4) for v in vals] for k, vals in history.items()} | {"test_accuracy": round(float(test_acc), 4)},
              open(ROOT / "training" / "history.json", "w"), indent=1)

    # samples for the JS parity test (web/test.js): proves the browser gives the same answers
    probs = net.forward(X_test[:25])
    json.dump([{"x": X_test[i].round(4).tolist(), "y": int(y_test[i]), "probs": probs[i].round(6).tolist()} for i in range(25)],
              open(ROOT / "web" / "test_samples.json", "w"))

    # ---------- charts ----------
    plt.style.use("seaborn-v0_8-whitegrid")
    ep = range(1, EPOCHS + 1)
    fig, (a1, a2) = plt.subplots(1, 2, figsize=(11, 4))
    a1.plot(ep, history["train_loss"], label="train", color="#4f46e5", lw=2)
    a1.plot(ep, history["test_loss"], label="test", color="#f97316", lw=2)
    a1.set(title="Loss (lower is better)", xlabel="epoch", ylabel="cross-entropy")
    a1.legend()
    a2.plot(ep, np.array(history["train_acc"]) * 100, label="train", color="#4f46e5", lw=2)
    a2.plot(ep, np.array(history["test_acc"]) * 100, label="test", color="#f97316", lw=2)
    a2.set(title=f"Accuracy (final test: {test_acc:.1%})", xlabel="epoch", ylabel="%", ylim=(85, 100.5))
    a2.legend()
    fig.tight_layout()
    fig.savefig(OUT / "training_curves.png", dpi=130)

    cm = np.zeros((10, 10), int)
    for t, p in zip(y_test, preds):
        cm[t, p] += 1
    fig, ax = plt.subplots(figsize=(5.5, 5))
    ax.imshow(cm, cmap="Blues")
    ax.grid(False)
    for i in range(10):
        for j in range(10):
            if cm[i, j]:
                ax.text(j, i, cm[i, j], ha="center", va="center", color="white" if cm[i, j] > cm.max() / 2 else "black")
    ax.set(title="Confusion matrix (test set)", xlabel="predicted", ylabel="actual", xticks=range(10), yticks=range(10))
    fig.tight_layout()
    fig.savefig(OUT / "confusion_matrix.png", dpi=130)

    fig, axes = plt.subplots(2, 8, figsize=(10, 3))
    for ax, img, t, p in zip(axes.flat, X_test[:16], y_test[:16], preds[:16]):
        ax.imshow(img.reshape(8, 8), cmap="gray_r")
        ax.set_title(f"pred {p}", color="green" if p == t else "red", fontsize=10)
        ax.axis("off")
    fig.suptitle("Sample test predictions (8x8 input images)")
    fig.tight_layout()
    fig.savefig(OUT / "sample_predictions.png", dpi=130)
    print("Saved charts to screenshots/ and model to web/model.js")


if __name__ == "__main__":
    main()
